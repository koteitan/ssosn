"""Coverage and final lower-unit expansion audit for [P,P1), length <= 18.

Run: timeout 60 python3 work/p1_lower43.py
Requires the table generated by p1_tokens43.py.
"""
from collections import Counter, defaultdict
import json
from pathlib import Path

import harness
import std
from p1_tokens43 import P, parse_all, token_map, normalize_tokens


def main():
    here = Path(__file__).resolve().parent
    data = json.loads((here / 'p1-tokens43-18.json').read_text())
    tm = token_map(18)
    tm.pop('E')  # E = A0 V
    tm['Z'] = (0,)
    for k in range(1, 18):
        tm[f'L{k}'] = (0,) + (1,)*k
    counts = Counter()
    examples = defaultdict(list)
    failures = []
    for digits in data['standard_raw']:
        raw = tuple(map(int, digits))
        forms = parse_all(raw[len(P):], tm, cap=10000)
        if not forms:
            failures.append({'raw': digits, 'reason': 'not parsed'})
            continue
        normalized = {normalize_tokens(form) for form in forms}
        if len(normalized) != 1:
            failures.append({'raw': digits, 'reason': 'canonical ambiguity',
                             'forms': [list(x) for x in sorted(normalized)]})
        counts['covered'] += 1
        counts['multiple_raw_parses' if len(forms)>1 else 'unique_raw_parse'] += 1
        words = next(iter(normalized))
        if not words or not words[-1].startswith('L'):
            continue
        k = int(words[-1][1:])
        start = len(raw) - len(tm[words[-1]])
        cut = harness.Seq(raw, 'new').cut()
        if cut == 2:
            kind = 'root_copy'
            good = raw[:2]
            block = raw[2:-1] + (0,)
        elif cut == start + 1:
            kind = 'local_lower_unit'
            good = raw[:start+1]
            block = (1,)*(k-1) + (0,)
        elif 2 < cut <= start and raw[cut-1] == 0:
            kind = 'earlier_lower_anchor'
            good = raw[:cut]
            block = raw[cut:-1] + (0,)
        else:
            kind = 'other_cut'
            good = raw[:cut]
            block = raw[cut:-1] + (0,)
        counts['final_lower'] += 1
        counts['final_lower_'+kind] += 1
        if cut > 2:
            offset = len(P)
            anchor = None
            for token in words:
                if offset == cut-1:
                    anchor = token
                    break
                offset += len(tm[token])
            if anchor is None or not (anchor in ('D', 'V') or anchor.startswith('L')):
                failures.append({'raw': digits, 'reason': 'cut not at lower head',
                                 'cut': cut, 'anchor': anchor})
            else:
                counts['anchor_'+anchor[0]] += 1
        if len(examples[kind]) < 12:
            examples[kind].append({'raw': digits, 'tokens': list(words),
                                   'cut': cut, 'good': list(good),
                                   'block': list(block)})
        if any(harness.fs(raw, n) != good+block*n for n in range(1, 6)):
            failures.append({'raw': digits, 'reason': 'term formula', 'cut': cut})
    witness = P+(0,0,0,1)
    assert parse_all(witness[len(P):], tm)
    assert not std.is_standard(witness)
    report = {'maxlen': data['maxlen'], 'counts': dict(counts),
              'examples': dict(examples), 'failures': failures,
              'accepted_nonstandard_witness': ''.join(map(str, witness))}
    path = here / 'p1-lower43.json'
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print('counts', dict(counts), 'failures', len(failures),
          'accepted_nonstandard', report['accepted_nonstandard_witness'])


if __name__ == '__main__':
    main()
