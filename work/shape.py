"""Check the experimental tree shape and regenerate finite Lean cut certificates.

Run from the repository root, with an external timeout, for example:
  timeout 30s python3 work/shape.py --max-tail-length 16
The greedy standard-form test is experimental; Lean certificates do not trust it.
"""
import argparse
import itertools
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / 'work')]
import conj
import harness
import std
import tree


def shape(t):
    """Forward-order Python counterpart of Lean StdShape."""
    blocks = [u for u in t if u != 'z']
    if not blocks:
        return True
    if t[0] == 'z' or not all(shape(u[1]) for u in blocks):
        return False
    previous = None
    gap = 0
    for u in t:
        if u == 'z':
            gap += 1
            continue
        if previous is not None:
            if gap != 2 or tree.flat((previous,)) < tree.flat((u,)):
                return False
        previous = u
        gap = 0
    return True


def lean_list(y):
    return '[' + ','.join(map(str, y)) + ']'


def write_certificates(path, samples, bound):
    lines = [
        'import SSOS.SequenceOrdinal',
        '',
        '/-! Generated by work/shape.py. Each cut is checked by the Lean kernel.',
        f'The table has {len(samples)} sources of total length at most {bound + 2}.',
        'Membership in this finite table is the explicit scope of these theorems.',
        'No completeness or unbounded standard-form theorem is claimed. -/',
        '',
        'namespace SSOS',
        'namespace FiniteCuts',
        '',
        'def CutForBits (Y : List ℕ) : Prop :=',
        '  match parse Y with',
        '  | .b u :: P => CutCorrect u P',
        '  | _ => False',
        '',
        'set_option maxRecDepth 10000',
        'set_option maxHeartbeats 4000000',
        '-- The same simplification list is used for heterogeneous generated batches.',
        'set_option linter.unusedSimpArgs false',
        '',
    ]
    batches = [samples[i:i+32] for i in range(0, len(samples), 32)]
    for i, batch in enumerate(batches):
        lines.extend([
            f'def batch{i} : List (List ℕ) := [',
            ',\n'.join('  ' + lean_list(y) for y in batch),
            ']', '',
            f'theorem cuts{i} : ∀ Y ∈ batch{i}, CutForBits Y := by',
            f'  simp only [batch{i}, List.mem_cons, List.not_mem_nil, or_false,',
            '    forall_eq_or_imp]',
            '  simp [CutForBits, parse, parseStep, snocOne, CutCorrect, encode,',
            '    parts, raiseBits, raiseBit, liftBits, liftBit]',
            '  decide +kernel', '',
            f'theorem binary{i} : ∀ Y ∈ batch{i}, Binary Y := by',
            f'  simp [batch{i}, Binary]', '',
        ])
    names = ', '.join(f'batch{i}' for i in range(len(batches)))
    lines.extend([
        f'def samples : List (List ℕ) := [{names}].flatten', '',
        f'theorem sample_count : samples.length = {len(samples)} := by decide +kernel', '',
        'theorem cuts : ∀ Y ∈ samples, CutForBits Y := by',
        '  simp only [samples, List.mem_flatten, List.mem_cons, List.not_mem_nil, or_false]',
        '  intro Y h',
        '  obtain ⟨b, hb, hY⟩ := h',
        '  rcases hb with ' + ' | '.join('rfl' for _ in batches),
    ])
    for i in range(len(batches)):
        lines.append(f'  · exact cuts{i} Y hY')
    lines.extend([
        '',
        'theorem binary : ∀ Y ∈ samples, Binary Y := by',
        '  simp only [samples, List.mem_flatten, List.mem_cons, List.not_mem_nil, or_false]',
        '  intro Y h',
        '  obtain ⟨b, hb, hY⟩ := h',
        '  rcases hb with ' + ' | '.join('rfl' for _ in batches),
    ])
    for i in range(len(batches)):
        lines.append(f'  · exact binary{i} Y hY')
    lines.extend([
        '',
        'theorem ordinal_spec (Y : List ℕ) (hY : Y ∈ samples) :',
        '    (∀ k, 1 ≤ k → o (Seq.fs ([0,0] ++ Y) k) < o ([0,0] ++ Y)) ∧',
        '    o ([0,0] ++ Y) = ⨆ n : ℕ, o (Seq.fs ([0,0] ++ Y) (n+1)) := by',
        '  have hcut := cuts Y hY',
        '  have hc := canonical_parse Y',
        '  have he : encode (parse Y) = [0,0] ++ Y := by',
        '    simp [encode, flat_parse Y (binary Y hY)]',
        '  cases hp : parse Y with',
        '  | nil => simp [CutForBits, hp] at hcut',
        '  | cons x P => cases x with',
        '    | z => simp [CutForBits, hp] at hcut',
        '    | b u =>',
        '      simp only [CutForBits, hp] at hcut',
        '      rw [hp] at hc he',
        '      rw [← he]',
        '      exact ⟨o_fs_lt_of_cutCorrect u P hc hcut,',
        '        o_fs_sup_of_cutCorrect u P hc hcut⟩',
        '', 'end FiniteCuts', 'end SSOS', '',
    ])
    path.write_text('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--max-tail-length', type=int, default=14)
    ap.add_argument('--write-certificates', type=Path)
    ap.add_argument('--certificate-tail-length', type=int, default=14)
    args = ap.parse_args()
    if not 0 <= args.certificate_tail_length <= args.max_tail_length <= 16:
        ap.error('require 0 <= certificate-tail-length <= max-tail-length <= 16')
    total = shapes = limits = 0
    samples = []
    for n in range(args.max_tail_length + 1):
        for y in itertools.product((0, 1), repeat=n):
            t = tree.parse(y)
            good = shape(t)
            s = (0, 0) + y
            if good != std.is_standard(s):
                raise AssertionError(('standard-shape mismatch', s, good))
            total += 1
            if not good:
                continue
            shapes += 1
            if not y or y[-1] != 1:
                continue
            limits += 1
            if conj.rcut(s) != harness.Seq(s).cut():
                raise AssertionError(('cut mismatch', s))
            for k in (1, 2, 3):
                if not shape(tree.E(t, k)):
                    raise AssertionError(('shape not preserved', s, k))
            if n <= args.certificate_tail_length:
                samples.append(y)
        print(f'tail length <= {n}: {total} binary tails, {shapes} shapes, {limits} limits', flush=True)
    if args.write_certificates:
        write_certificates(args.write_certificates, samples, args.certificate_tail_length)
        print(f'wrote {len(samples)} finite cut certificates')


if __name__ == '__main__':
    main()
